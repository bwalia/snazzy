"""Generates src/fold_table.rs: python3 -I tools/gen_fold_table.py > src/fold_table.rs

Search folding (docs/specs/search.md) ignores accents the way Foundation's
diacritic-insensitive folding does: a letter whose canonical decomposition is a
base letter plus nonspacing marks becomes that base letter. Letters without a
decomposition (Ø, Ł, Æ, Œ) stay as they are, as on the Mac.
"""
import sys
import unicodedata


def base(c):
    d = unicodedata.normalize("NFD", c)
    if len(d) > 1 and all(unicodedata.category(x) == "Mn" for x in d[1:]):
        return d[0]
    return None


RANGES = [(0xC0, 0x24F), (0x370, 0x3FF), (0x400, 0x4FF), (0x1E00, 0x1EFF), (0x1F00, 0x1FFF)]

strip = []
for a, b in RANGES:
    for cp in range(a, b + 1):
        r = base(chr(cp))
        if r and r != chr(cp):
            strip.append((cp, ord(r)))

width = []
for cp in list(range(0xFF61, 0xFFA0)) + list(range(0xFFE0, 0xFFE7)) + [0x3000]:
    n = unicodedata.normalize("NFKC", chr(cp))
    if len(n) == 1 and n != chr(cp):
        width.append((cp, ord(n)))

out = sys.stdout
out.write("// Generated by tools/gen_fold_table.py from Unicode %s data. Do not edit.\n\n" % unicodedata.unidata_version)
out.write("/// Precomposed letters (Latin, Greek, Cyrillic) whose canonical decomposition is a\n")
out.write("/// base letter plus nonspacing marks, mapped to that base letter. Sorted.\n")
out.write("pub(crate) static STRIP: &[(char, char)] = &[\n")
for a, b in strip:
    out.write("    ('\\u{%04X}', '\\u{%04X}'),\n" % (a, b))
out.write("];\n\n")
out.write("/// Halfwidth forms (katakana, symbols) and the ideographic space, mapped to their\n")
out.write("/// compatibility (NFKC) equivalents. Sorted.\n")
out.write("pub(crate) static WIDTH: &[(char, char)] = &[\n")
for a, b in sorted(width):
    out.write("    ('\\u{%04X}', '\\u{%04X}'),\n" % (a, b))
out.write("];\n")
